run_status() {
  local output="$1"
  shift
  local status
  set +e
  "$@" > "${output}" 2>&1
  status=$?
  set -e
  printf '%s' "${status}"
}

test_source_guard_and_parser() {
  local case_dir output status
  case_dir="${TEST_TMP}/parser"
  mkdir -p "${case_dir}"
  setup_case parser
  output="${case_dir}/output.log"
  assert_eq true "${CLI_SOURCED}" "sourced CLI guard"
  if ! CONFIG_DIR="${case_dir}/attacker" bash -c '
    source "$1"
    [[ "${CONFIG_DIR}" == "/etc/bupt-ec" && "${PRIVATE_ENV_FILE}" == "/etc/bupt-ec/bupt-ec.env" ]]
  ' _ "${CLI_TEST_SCRIPT_DIR}/bupt-ec-cli.sh"; then
    fail "production CLI accepted caller path overrides"
  fi

  status="$(run_status "${output}" bash "${CLI_TEST_SCRIPT_DIR}/bupt-ec-cli.sh")"
  assert_eq 0 "${status}" "direct no-argument help status"
  assert_contains "${output}" "Usage: bupt-ec" "direct no-argument help"
  status="$(run_status "${output}" cli_main)"
  assert_eq 0 "${status}" "no-argument help status"
  assert_contains "${output}" "Usage: bupt-ec" "no-argument help"
  status="$(run_status "${output}" cli_main --help)"
  assert_eq 0 "${status}" "long help status"
  status="$(run_status "${output}" cli_main -h extra)"
  assert_eq 2 "${status}" "extra help argument status"

  : > "${MOCK_CURL_LOG}"
  status="$(run_status "${output}" cli_main unknown)"
  assert_eq 2 "${status}" "unknown command status"
  status="$(run_status "${output}" cli_main status extra)"
  assert_eq 2 "${status}" "status extra argument status"
  status="$(run_status "${output}" cli_main update v0.3.1 extra)"
  assert_eq 2 "${status}" "update extra argument status"
  status="$(run_status "${output}" cli_main update invalid)"
  assert_eq 2 "${status}" "invalid update version status"
  status="$(run_status "${output}" cli_main update "")"
  assert_eq 2 "${status}" "empty update version status"
  status="$(run_status "${output}" cli_main logs -n 0)"
  assert_eq 2 "${status}" "invalid logs count status"
  status="$(run_status "${output}" cli_main logs -f -f)"
  assert_eq 2 "${status}" "duplicate logs follow status"
  [[ ! -s "${MOCK_CURL_LOG}" ]] || fail "parser error reached curl"
  [[ ! -s "${MOCK_SYSTEMCTL_LOG}" ]] || fail "parser error reached systemctl"
}

test_root_matrix() {
  local case_dir output status command
  case_dir="${TEST_TMP}/root-matrix"
  mkdir -p "${case_dir}"
  setup_case root-matrix
  output="${case_dir}/output.log"

  # CI normally uses a non-root runner, but the behavior suite must also stay
  # meaningful when a maintainer invokes it as root. The production guard has
  # no environment override, so exercise its success branch directly there.
  if [[ "${EUID}" -eq 0 ]]; then
    for command in update config start stop restart; do
      require_cli_root "${command}" || fail "${command} root gate rejected root"
    done
    require_cli_root config show || fail "config show root gate rejected root"
    return
  fi

  for command in \
    "update" \
    "update v0.3.1" \
    "config" \
    "config show" \
    "start" \
    "stop" \
    "restart"
  do
    # shellcheck disable=SC2206
    local -a arguments=( ${command} )
    status="$(run_status "${output}" cli_main "${arguments[@]}")"
    assert_eq 1 "${status}" "${command} non-root status"
    assert_contains "${output}" "sudo bupt-ec ${command}" "${command} sudo guidance"
  done
  [[ ! -s "${MOCK_CURL_LOG}" ]] || fail "non-root command reached curl"
  [[ ! -s "${MOCK_SYSTEMCTL_LOG}" ]] || fail "non-root command reached systemctl"
}

test_private_config_loader_and_redaction() {
  local case_dir output status frame_dir target
  case_dir="${TEST_TMP}/private-loader"
  mkdir -p "${case_dir}"
  setup_case private-loader
  write_private_config
  cat >> "${PRIVATE_ENV_FILE}" <<'EOF'
ALLOW_INSECURE_DOWNLOAD_BASE_URL=true
SKIP_CHECKSUM=1
CLI_BUILD_VERSION=mutated
EOF
  frame_dir="${case_dir}/frames"
  mkdir -p "${frame_dir}"
  mktemp() {
    if [[ "${1:-}" == "/tmp/${SERVICE_NAME}-cli-config.XXXXXX" ]]; then
      command mktemp "${frame_dir}/frame.XXXXXX"
    else
      command mktemp "$@"
    fi
  }
  load_private_deployment_config
  unset -f mktemp
  [[ -z "$(find "${frame_dir}" -mindepth 1 -print -quit)" ]] || fail "private frame cleanup"
  assert_eq ming-kang/BUPT_EC "${PRIVATE_RELEASE_REPO}" "private repository frame"
  assert_eq v0.3.1 "${PRIVATE_RELEASE_VERSION}" "private version frame"
  [[ -z "${ALLOW_INSECURE_DOWNLOAD_BASE_URL+x}" ]] || fail "private env activated insecure switch"
  assert_eq dev "${CLI_BUILD_VERSION}" "private env mutated CLI state"

  output="${case_dir}/show.log"
  show_config > "${output}"
  assert_contains "${output}" "JW_PASSWORD=***" "config show password redaction"
  assert_contains "${output}" "JW_TOKEN=***" "config show token redaction"
  assert_not_contains "${output}" "private-password-secret" "config show password disclosure"
  assert_not_contains "${output}" "private-token-secret" "config show token disclosure"

  cat > "${PRIVATE_ENV_FILE}" <<'EOF'
printf '%s\n' 'source-stdout-secret'
printf '%s\n' 'source-stderr-secret' >&2
trap 'printf "%s" "exit-trap-secret"' EXIT
EOF
  chmod 0600 "${PRIVATE_ENV_FILE}"
  output="${case_dir}/unsafe-source.log"
  mktemp() {
    if [[ "${1:-}" == "/tmp/${SERVICE_NAME}-cli-config.XXXXXX" ]]; then
      command mktemp "${frame_dir}/failure-frame.XXXXXX"
    else
      command mktemp "$@"
    fi
  }
  status="$(run_status "${output}" load_private_deployment_config)"
  unset -f mktemp
  assert_eq 1 "${status}" "unsafe private source status"
  [[ -z "$(find "${frame_dir}" -mindepth 1 -print -quit)" ]] || fail "unsafe private frame cleanup"
  assert_contains "${output}" "Failed to load existing configuration safely." "unsafe private source error"
  assert_not_contains "${output}" "source-stdout-secret" "source stdout redaction"
  assert_not_contains "${output}" "source-stderr-secret" "source stderr redaction"
  assert_not_contains "${output}" "exit-trap-secret" "source trap redaction"

  write_private_config
  if [[ "${POSIX_MODES_SUPPORTED}" == "true" ]]; then
    chmod 0644 "${PRIVATE_ENV_FILE}"
  else
    CLI_TEST_PRIVATE_MODE=644
  fi
  output="${case_dir}/unsafe-mode.log"
  status="$(run_status "${output}" load_private_deployment_config)"
  assert_eq 1 "${status}" "unsafe private mode status"
  assert_not_contains "${output}" "private-password-secret" "unsafe private mode redaction"

  CLI_TEST_PRIVATE_MODE=600
  write_private_config
  CLI_EXPECTED_UID=$((EUID + 1))
  output="${case_dir}/unsafe-owner.log"
  status="$(run_status "${output}" load_private_deployment_config)"
  assert_eq 1 "${status}" "unsafe private owner status"
  assert_not_contains "${output}" "private-token-secret" "unsafe private owner redaction"
  CLI_EXPECTED_UID="${EUID}"

  if [[ "${POSIX_MODES_SUPPORTED}" == "true" ]]; then
    target="${case_dir}/private-target"
    write_private_config
    cp "${PRIVATE_ENV_FILE}" "${target}"
    rm -f -- "${PRIVATE_ENV_FILE}"
    ln -s "${target}" "${PRIVATE_ENV_FILE}"
    output="${case_dir}/private-symlink.log"
    status="$(run_status "${output}" load_private_deployment_config)"
    assert_eq 1 "${status}" "private symlink status"
    assert_not_contains "${output}" "private-password-secret" "private symlink redaction"

    rm -f -- "${PRIVATE_ENV_FILE}"
    write_private_config
    chmod 0777 "${CONFIG_DIR}"
    output="${case_dir}/private-parent.log"
    status="$(run_status "${output}" load_private_deployment_config)"
    assert_eq 1 "${status}" "writable private parent status"
    chmod 0755 "${CONFIG_DIR}"
  fi

  # A sourced test shell can carry readonly variables into the isolated child.
  # The loader must reject rather than framing a caller value if it cannot
  # clear the fixed registry first.
  write_private_config
  readonly RELEASE_REPO="caller-private-repository"
  output="${case_dir}/readonly-inherited.log"
  status="$(run_status "${output}" load_private_deployment_config)"
  assert_eq 1 "${status}" "readonly inherited registry status"
  assert_not_contains "${output}" "caller-private-repository" "readonly registry redaction"
}


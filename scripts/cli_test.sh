POSIX_MODES_SUPPORTED=true
case "$(uname -s)" in
  MINGW* | MSYS* | CYGWIN*) POSIX_MODES_SUPPORTED=false ;;
esac

# Windows-backed fixtures cannot retain exact POSIX modes. Production code keeps
# its strict checks; only this sourced suite supplies synthetic stat modes.
if [[ "${POSIX_MODES_SUPPORTED}" == "false" ]]; then
  stat() {
    if [[ "${1:-}" == "-c" && "${3:-}" == "--" ]]; then
      case "${2:-}|${4:-}" in
        "%a|${PRIVATE_ENV_FILE}")
          printf '%s\n' "${CLI_TEST_PRIVATE_MODE:-600}"
          return 0
          ;;
        "%a|${DEPLOYMENT_METADATA_FILE}")
          printf '%s\n' "${CLI_TEST_METADATA_MODE:-644}"
          return 0
          ;;
      esac
    fi
    command stat "$@"
  }
fi

fail() {
  echo "FAIL: $*" >&2
  exit 1
}

assert_eq() {
  local want="$1" got="$2" label="$3"
  [[ "${got}" == "${want}" ]] || fail "${label}: got '${got}', want '${want}'"
}

assert_contains() {
  local path="$1" text="$2" label="$3"
  grep -Fq -- "${text}" "${path}" || fail "${label}: '${text}' not found"
}

assert_not_contains() {
  local path="$1" text="$2" label="$3"
  if grep -Fq -- "${text}" "${path}"; then
    fail "${label}: unexpected '${text}'"
  fi
}

assert_path_absent() {
  local path="$1" label="$2"
  [[ ! -e "${path}" && ! -L "${path}" ]] || fail "${label}: ${path} remains"
}

assert_mode() {
  local path="$1" want="$2" label="$3" got
  [[ "${POSIX_MODES_SUPPORTED}" == "true" ]] || return
  got="$(command stat -c '%a' "${path}")"
  assert_eq "${want}" "${got}" "${label} mode"
}

